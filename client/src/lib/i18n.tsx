export type TranslationKey = keyof typeof translations
const dict = translations

interface I18nContextValue {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

// Language switching has been disabled: the multi-language translations
// across the app's pages were incomplete and inconsistent (a mix of
// English/Gujarati/Hindi appearing together), which was a worse experience
// than a single consistent language. The dictionary and t() plumbing stay
// in place below so this can be revisited properly later, but lang is now
// hard-locked to English and setLang is a no-op - it deliberately ignores
// any language previously saved to localStorage by earlier versions of the
// app, so a returning user's browser doesn't silently switch them to a
// half-translated Gujarati/Hindi experience.
export function I18nProvider({ children }: { children: React.ReactNode }) {
  const lang: Lang = 'en'

  useEffect(() => {
    document.documentElement.lang = lang
  }, [])

  const setLang = (_l: Lang) => { /* language switching disabled - see comment above */ }
  // Supports simple {{placeholder}} interpolation, e.g. t('greeting', { name: 'Raj' })
  // for strings whose dynamic part (a name, a count) shouldn't itself be translated.
  const t = (key: TranslationKey, vars?: Record<string, string | number>): string => {
    let str = dict[key]?.[lang] ?? dict[key]?.en ?? String(key)
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`{{${k}}}`, 'g'), String(v))
      }
    }
    return str
  }

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within an I18nProvider')
  return ctx
}
